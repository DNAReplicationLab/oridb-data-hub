#!/usr/bin/env python3
"""Build or refresh one dataset's stanza in the OriDB data hub.

The hub is organised one directory per dataset under <genome>/, each with its own
trackDb.txt, and the genome-level trackDb.txt is nothing but `include` lines. That way a
new dataset is added without touching any existing dataset's configuration, and a dataset
can be regenerated by its own pipeline without the hub maintainer merging anything.

Time courses are rendered as a multiWig overlay rather than as separate rows: the point of
a replication time course is how the profiles stack up against each other at the same
locus, which a reader can only see when they are superimposed.
"""
import argparse, json, os, re, sys

# Colours for the sync-seq time course follow Müller et al. 2014 Figure 3D, so a reader
# moving between the paper and the browser sees the same timepoint in the same colour.
TIMEPOINT_COLOURS = {
    25: ("166,206,227", "light blue"),
    30: ("227,26,28",   "red"),
    35: ("31,120,180",  "blue"),
    40: ("255,193,7",   "gold"),
    45: ("51,160,44",   "green"),
    50: ("106,61,154",  "purple"),
    90: ("150,150,150", "grey"),
}
FALLBACK_COLOURS = ["27,120,55", "117,112,179", "217,95,2", "231,41,138",
                    "102,166,30", "230,171,2", "166,118,29", "102,102,102"]

VARIANT = {
    "sortseq": ("Sort-seq", "FACS-sorted S phase versus G2 phase"),
    "syncseq": ("Sync-seq", "synchronous S-phase time course, each timepoint versus the "
                            "alpha-factor arrest"),
    "mfaseq":  ("MFA-seq",  "exponential versus stationary phase"),
    "hu":      ("HU origin mapping", "forks stalled at origins by hydroxyurea"),
    "trep":    ("Trep",     "median replication time from the sync-seq time course"),
}


def classify(track_name):
    if "trep" in track_name:
        return "trep"
    for key in VARIANT:
        if key in track_name:
            return key
    return "other"


def timepoint(track_name):
    m = re.search(r"(\d+)min", track_name)
    return int(m.group(1)) if m else None


def clean(name):
    for suffix in (".smooth", ".ratio", ".trep"):
        if name.endswith(suffix):
            return name[: -len(suffix)]
    return name


def stanzas(dataset, tracks, descriptions, viewlimits):
    """trackDb text for one dataset: a container per experimental variant."""
    out = []
    groups = {}
    for bw in tracks:
        groups.setdefault(classify(bw[:-3]), []).append(bw)

    for variant, files in sorted(groups.items()):
        label, blurb = VARIANT.get(variant, (variant, variant))
        parent = f"{dataset}_{variant}"
        is_course = variant == "syncseq" and len(files) > 1
        lims = viewlimits.get(variant, "1:2")

        if is_course:
            # One overlaid track: superimposing the timepoints is the whole point.
            #
            # Latest timepoint first, because in a transparentOverlay the subtracks are
            # drawn in the order they appear and each one paints over its predecessors.
            # The last timepoint is the highest and the flattest — by 90 min the genome is
            # replicated and the profile sits near 2 across its whole length — so drawing
            # it last buries the early timepoints, which are the ones carrying the
            # structure a reader is looking for. Reversing puts the earliest, most
            # detailed profile on top.
            files = sorted(files, key=lambda f: (timepoint(f[:-3]) or 0), reverse=True)
            # solidOverlay, not transparentOverlay. With seven overlapping profiles,
            # transparency blends every colour into a wash and nothing reads clearly;
            # drawing each one solid, latest first, gives the later timepoints as a
            # backdrop with the earlier, more structured ones legible in front. This is
            # the configuration proven on the lab's sacCer1 hub.
            out.append(
                f"track {parent}\n"
                f"container multiWig\n"
                f"aggregate solidOverlay\n"
                f"showSubtrackColorOnUi on\n"
                f"shortLabel {label}\n"
                f"longLabel {dataset}: {label} — {blurb}\n"
                f"type bigWig\n"
                f"viewLimits {lims}\n"
                f"autoScale off\n"
                f"alwaysZero off\n"
                f"graphTypeDefault bar\n"
                # A line at copy number 1 is the unreplicated baseline: it tells the
                # reader where "not yet replicated" sits without reading the axis.
                f"yLineOnOff on\n"
                f"yLineMark 1.0\n"
                f"gridDefault off\n"
                f"maxHeightPixels 100:32:8\n"
                f"visibility full\n"
                f"priority 2\n\n")
        else:
            out.append(
                f"track {parent}\n"
                f"compositeTrack on\n"
                f"shortLabel {label}\n"
                f"longLabel {dataset}: {label} — {blurb}\n"
                f"type bigWig\n"
                f"viewLimits {lims}\n"
                f"autoScale off\n"
                f"graphTypeDefault bar\n"
                + ("" if variant == "trep" else "yLineOnOff on\nyLineMark 1.0\n")
                + f"gridDefault off\n"
                f"maxHeightPixels 100:32:8\n"
                f"visibility full\n"
                f"priority {1 if variant == 'sortseq' else 3}\n\n")

        for i, bw in enumerate(files):
            name = clean(bw[:-3])
            tp = timepoint(name)
            if is_course and tp in TIMEPOINT_COLOURS:
                colour, colour_name = TIMEPOINT_COLOURS[tp]
                # The track-controls list sorts subtracks by shortLabel, so without a
                # prefix it would read 25, 30, 35, 40, 45, 50, 90 - the opposite of the
                # draw order, which has to run latest-first so the early timepoints are
                # not buried. Numbering by draw position makes the list match what the
                # reader sees stacked in the image.
                short = f"{i + 1} {tp} min"
                long_ = descriptions.get(name, f"{tp} min after release") + f" ({colour_name})"
            else:
                colour = FALLBACK_COLOURS[i % len(FALLBACK_COLOURS)]
                short = name[:17]
                long_ = descriptions.get(name, name)
            # UCSC resolves bigDataUrl relative to the trackDb named in genomes.txt -
            # <genome>/trackDb.txt - NOT relative to the file an `include` pulled it from.
            # The dataset directory therefore has to be part of the path, or the browser
            # looks for <genome>/<file>.bw and reports that it cannot open the track.
            out.append(
                f"    track {name}\n"
                f"    parent {parent} on\n"
                f"    bigDataUrl {dataset}/{bw}\n"
                f"    shortLabel {short}\n"
                f"    longLabel {long_}\n"
                f"    type bigWig\n"
                f"    color {colour}\n"
                + (f"    graphTypeDefault points\n" if variant == "trep" else "")
                + "\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub-root", required=True, help="repository root holding hub.txt")
    ap.add_argument("--genome", default="sacCer3")
    ap.add_argument("--dataset", required=True, help="directory name under <genome>/")
    ap.add_argument("--bigwig-dir", required=True, help="where the .bw files are now")
    ap.add_argument("--descriptions", help="TSV: track name <tab> long label")
    ap.add_argument("--dataset-json", help="dataset record to copy in alongside the tracks")
    # 0.9:2.1 rather than a hard 1:2. The scale that means something is still 1
    # (unreplicated) to 2 (fully replicated), and the yLineMark draws that baseline, but
    # smoothed profiles overshoot both ends slightly and a hard 1:2 flattens those
    # excursions against the edge of the track, which is what makes a crowded overlay
    # unreadable. A little headroom keeps the shape visible without changing the scale.
    ap.add_argument("--viewlimits",
                    default="syncseq=0.9:2.1,sortseq=0.9:2.1,mfaseq=0.9:1.5,hu=0.9:2.1,trep=25:85",
                    help="per-variant viewLimits, comma separated")
    ap.add_argument("--no-copy", action="store_true", help="write trackDb only")
    a = ap.parse_args()

    viewlimits = dict(p.split("=", 1) for p in a.viewlimits.split(",") if "=" in p)
    descriptions = {}
    if a.descriptions and os.path.exists(a.descriptions):
        for line in open(a.descriptions):
            if "\t" in line:
                k, v = line.rstrip("\n").split("\t", 1)
                descriptions[k] = v

    dest = os.path.join(a.hub_root, a.genome, a.dataset)
    os.makedirs(dest, exist_ok=True)

    tracks = sorted(f for f in os.listdir(a.bigwig_dir) if f.endswith(".bw"))
    if not tracks:
        sys.exit(f"no .bw files in {a.bigwig_dir}")
    if not a.no_copy:
        import shutil
        for bw in tracks:
            src = os.path.join(a.bigwig_dir, bw)
            if os.path.abspath(src) != os.path.abspath(os.path.join(dest, bw)):
                shutil.copy2(src, os.path.join(dest, bw))
        if a.dataset_json:
            shutil.copy2(a.dataset_json, os.path.join(dest, "dataset.json"))

    with open(os.path.join(dest, "trackDb.txt"), "w") as fh:
        fh.write(f"# {a.dataset} — generated by bin/make_trackhub.py; edit the generator, "
                 f"not this file\n\n")
        fh.write(stanzas(a.dataset, tracks, descriptions, viewlimits))

    # genome-level trackDb is only include lines, so datasets never collide
    genome_dir = os.path.join(a.hub_root, a.genome)
    datasets = sorted(d for d in os.listdir(genome_dir)
                      if os.path.isdir(os.path.join(genome_dir, d))
                      and os.path.exists(os.path.join(genome_dir, d, "trackDb.txt")))
    with open(os.path.join(genome_dir, "trackDb.txt"), "w") as fh:
        fh.write("# One include per dataset. Add a dataset with bin/make_trackhub.py;\n"
                 "# this file is regenerated from the directories present.\n\n")
        for d in datasets:
            fh.write(f"include {d}/trackDb.txt\n")

    print(f"{a.dataset}: {len(tracks)} tracks -> {dest}/trackDb.txt")
    print(f"{a.genome}/trackDb.txt now includes: {', '.join(datasets)}")


if __name__ == "__main__":
    main()
