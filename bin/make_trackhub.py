#!/usr/bin/env python3
"""Build or refresh one dataset's stanza in the OriDB data hub.

The hub is organised one directory per dataset under <genome>/, each with its own
trackDb.txt, and the genome-level trackDb.txt is nothing but `include` lines. A new
dataset is added without touching any existing dataset's configuration.

Containers are COMPARISONS, not file groupings. Which profiles belong side by side is a
curation decision that cannot be inferred from filenames - the same track legitimately
appears in more than one comparison - so it is declared in a spec file per dataset and
this script only renders it. Use --init to generate a starter spec from a directory of
bigWigs, then edit it.

Every container is a multiWig solidOverlay: overlaying the profiles being compared is
what makes a difference visible, which separate stacked rows cannot do.

Containers sit inside SECTIONS - UCSC supertracks, the folders a reader sees in the track
controls. Sections are declared once for the whole hub in docs/sections.json and rendered
to <genome>/sections.trackDb.txt; a dataset says only which section each container belongs
to, so adding a dataset still never edits another dataset's configuration. Every section
is closed by default (`superTrack on`) except the overview, which carries `show`: that is
what keeps the number of tracks drawn on first load independent of how many datasets the
hub holds.
"""
import argparse, json, os, shutil, sys


def render(dataset, spec, section_ids=()):
    out = [f"# {dataset} - generated by bin/make_trackhub.py from the container spec;\n"
           f"# edit the spec and regenerate, do not edit this file\n\n"]

    default_section = spec.get("section")

    def section_of(item):
        """Which supertrack this container or track belongs in."""
        sec = item.get("section", default_section)
        if sec is None:
            sys.exit(f"{dataset}: '{item['id']}' has no section and the spec sets no "
                     f"default; add \"section\": \"<id>\" to the spec")
        if section_ids and sec not in section_ids:
            sys.exit(f"{dataset}: '{item['id']}' names section {sec!r}, which is not "
                     f"defined in the sections file ({', '.join(sorted(section_ids))})")
        return f"oridb_{sec}"

    for c in spec["containers"]:
        parent = f"{dataset}_{c['id']}"
        # maxHeightPixels is max:default:min - the MIDDLE value is the height actually
        # drawn. A default of 32 renders a track a third of its usable size, which is
        # the usual reason a signal track looks cramped.
        lines = [
            f"track {parent}",
            f"parent {section_of(c)}",
            "container multiWig",
            "aggregate solidOverlay",
            "showSubtrackColorOnUi on",
            f"shortLabel {c['shortLabel']}",
            f"longLabel {c['longLabel']}",
            "type bigWig",
            f"viewLimits {c['viewLimits']}",
        ]
        # autoScale: "off" (the default) honours viewLimits; "group" lets the browser
        # scale the y-axis to the current window, shared across every track in this
        # container so an overlay still compares like with like. "group" belongs on the
        # container only, never on a child - UCSC reads it from the parent. It is the
        # answer for a measurement whose dynamic range no fixed window covers, at the
        # cost of a scale that changes as the reader scrolls, and of background noise
        # filling the track in a window that contains no signal.
        auto = c.get("autoScale", "off")
        if auto not in ("off", "on", "group"):
            sys.exit(f"{dataset}: container '{c['id']}' has autoScale {auto!r}; "
                     f"UCSC accepts only off, on or group")
        lines.append(f"autoScale {auto}")
        # With a scale that moves, the zero line has to be pinned or the axis can float
        # away from it - which would make a signed strand track unreadable.
        lines.append("alwaysZero " + ("on" if auto != "off" else "off"))
        lines.append(f"graphTypeDefault {c.get('graphType', 'bar')}")
        if c.get("negateValues"):
            # Flip the sign so that an early replication time plots high, consistent
            # with the copy-number tracks where high means more replicated.
            lines.append("negateValues on")
        if c.get("yLineMark") is not None:
            lines += ["yLineOnOff on", f"yLineMark {c['yLineMark']}"]
        else:
            lines.append("yLineOnOff off")
        lines += [
            "gridDefault off",
            f"maxHeightPixels {c.get('maxHeightPixels', '100:100:8')}",
            "visibility full",
            f"priority {c.get('priority', 10)}",
            "",
        ]
        out.append("\n".join(lines) + "\n")

        for t in c["tracks"]:
            # Track names must be unique across the whole hub, but a comparison may
            # reuse a file that another comparison also shows, so the container id is
            # part of the name.
            name = f"{c['id']}_{os.path.basename(t['file'])[:-3].replace('.', '_')}"
            sub = [
                f"    track {name}",
                f"    parent {parent} on",
                f"    bigDataUrl {dataset}/{t['file']}",
                f"    shortLabel {t['shortLabel']}",
                f"    longLabel {t['longLabel']}",
                "    type bigWig",
                f"    color {t['color']}",
            ]
            if t.get("altColor"):
                # Negated wiggles are drawn in altColor, not color.
                sub.append(f"    altColor {t['altColor']}")
            out.append("\n".join(sub) + "\n\n")

    # Standalone tracks: anything that is not a signal profile to be overlaid.
    # A call set is a feature track, not a comparison - putting it in a multiWig
    # container would be a category error, so it is rendered on its own.
    for t in spec.get("tracks", []):
        lines = [
            f"track {dataset}_{t['id']}",
            f"parent {section_of(t)}",
            f"bigDataUrl {dataset}/{t['file']}",
            f"shortLabel {t['shortLabel']}",
            f"longLabel {t['longLabel']}",
            f"type {t.get('type', 'bigBed')}",
            f"visibility {t.get('visibility', 'pack')}",
            f"color {t.get('color', '0,0,0')}",
        ]
        if t.get("spectrum"):
            # Shades each feature by its score column, so a weak call is visibly weak.
            lines += ["useScore 1", "spectrum on"]
            if t.get("scoreMin") is not None:
                lines.append(f"scoreMin {t['scoreMin']}")
        lines += feature_track_options(t)
        lines += [f"priority {t.get('priority', 10)}", ""]
        out.append("\n".join(lines) + "\n")
    return "".join(out)



def assembly_hub_genomes(hub_root):
    """Which genomes this hub supplies the sequence for, read from genomes.txt.

    A genome with a `twoBitPath` is not a UCSC database: the browser has no groups,
    no description page and no `db=` for it, and UCSC requires the hub to provide
    all three. A genome without one is a UCSC assembly and must NOT be given them -
    its tracks belong in UCSC's own groups.
    """
    hub = set()
    genome = None
    for line in open(os.path.join(hub_root, "genomes.txt")):
        line = line.strip()
        if line.startswith("genome "):
            genome = line.split()[1]
        elif line.startswith("twoBitPath ") and genome:
            hub.add(genome)
    return hub


def render_groups(sections, used):
    """groups.txt for an assembly hub: one track group per section in use.

    UCSC groups the track controls under the browser image by group, and for an
    assembly hub there are no native groups to fall back on. Mirroring the sections
    keeps one vocabulary: a supertrack named in sections.json claims the group of
    the same name, and a section nobody uses is not emitted here either.
    """
    out = ["# Generated by bin/make_trackhub.py from docs/sections.json;\n"
           "# edit that file and regenerate, do not edit this one.\n\n"]
    ov = sections["overview"]
    entries = [(f"oridb_{ov['id']}", ov["shortLabel"], ov.get("priority", 0), "0")]
    for s in sorted(sections["sections"], key=lambda x: x.get("priority", 99)):
        if f"oridb_{s['id']}" in used:
            entries.append((f"oridb_{s['id']}", s["shortLabel"], s.get("priority", 99), "1"))
    for name, label, priority, closed in entries:
        out.append("\n".join([
            f"name {name}",
            f"label {label}",
            f"priority {priority}",
            f"defaultIsClosed {closed}",
            "", ""]))
    return "".join(out)


def feature_track_options(t):
    """Settings a bigBed track may carry that a bigWig one cannot.

    `itemRgb` hands the colour to the file, which is how a track can draw one
    feature per tier without one track per tier. `url` turns every feature name
    into a link back to the record it came from, so a reader who finds an OriDB
    feature in a browser can reach the page that explains it. `searchIndex`
    requires the bigBed to have been built with a matching -extraIndex.
    """
    lines = []
    if t.get("itemRgb"):
        lines.append("itemRgb on")
    if t.get("url"):
        lines.append(f"url {t['url']}")
        if t.get("urlLabel"):
            lines.append(f"urlLabel {t['urlLabel']}")
    if t.get("searchIndex"):
        lines.append(f"searchIndex {t['searchIndex']}")
    if t.get("panelDefault"):
        # A second, narrower notion of "drawn by default" than the overview, and the
        # reason it exists: the embedded JBrowse panel in oridb-v3 has no annotation of
        # its own, while UCSC serves SGD Genes on sacCer3 already. A gene track put in
        # the overview to reach the panel would be drawn on top of UCSC's own copy for
        # every UCSC reader. `metadata` is a free-form trackDb setting that UCSC shows
        # in the track description and otherwise ignores, so the hub can say this
        # without changing what UCSC draws. bin/build_datahub.php in oridb-v3 reads it.
        lines.append("metadata panelDefault=on")
    return lines


def render_overview_container(t, overview_id):
    """An overview entry naming several files, rendered as a multiWig container.

    Same shape as a dataset container - the overview is simply its parent instead of a
    section - so the two kinds of overlay stay one thing to read and one thing to learn.
    A container does have siblings to share a scale with, so unlike a stand-alone
    overview track this one accepts autoScale group.
    """
    auto = t.get("autoScale", "off")
    if auto not in ("off", "on", "group"):
        sys.exit(f"overview container '{t['id']}' has autoScale {auto!r}; "
                 f"UCSC accepts only off, on or group")
    lines = [
        f"track {t['id']}",
        f"parent oridb_{overview_id}",
        "container multiWig",
        "aggregate solidOverlay",
        "showSubtrackColorOnUi on",
        f"shortLabel {t['shortLabel']}",
        f"longLabel {t['longLabel']}",
        "type bigWig",
        f"viewLimits {t['viewLimits']}",
        f"autoScale {auto}",
        "alwaysZero " + ("on" if auto != "off" else "off"),
        f"graphTypeDefault {t.get('graphType', 'bar')}",
    ]
    if t.get("yLineMark") is not None:
        lines += ["yLineOnOff on", f"yLineMark {t['yLineMark']}"]
    else:
        lines.append("yLineOnOff off")
    lines += ["gridDefault off",
              f"maxHeightPixels {t.get('maxHeightPixels', '100:100:8')}",
              f"visibility {t.get('visibility', 'full')}",
              f"priority {t.get('priority', 10)}", "", ""]
    out = ["\n".join(lines)]
    for f in t["files"]:
        sub = [f"    track {t['id']}_{os.path.basename(f['file'])[:-3].replace('.', '_')}",
               f"    parent {t['id']} on",
               f"    bigDataUrl {t['dataset']}/{f['file']}",
               f"    shortLabel {f['shortLabel']}",
               f"    longLabel {f['longLabel']}",
               "    type bigWig",
               f"    color {f['color']}"]
        if f.get("altColor"):
            # UCSC draws values below the axis in altColor, so a minus-strand
            # subtrack without it comes out in the default colour, not its own.
            sub.append(f"    altColor {f['altColor']}")
        out.append("\n".join(sub) + "\n\n")
    return "".join(out)


def render_sections(sections, used, datasets=(), group=False):
    """Render the supertrack declarations and the overview section.

    Only sections that a dataset actually uses are emitted: an empty folder in the track
    controls is noise. Every section is closed (`superTrack on`); the overview alone
    carries `show`, so the hub draws a fixed handful of tracks on first load whatever the
    catalogue grows to.
    """
    ov = sections["overview"]
    out = ["# Generated by bin/make_trackhub.py from docs/sections.json;\n"
           "# edit that file and regenerate, do not edit this one.\n\n"]

    overview = [
        f"track oridb_{ov['id']}",
        "superTrack on show",
        f"shortLabel {ov['shortLabel']}",
        f"longLabel {ov['longLabel']}",
    ]
    # On an assembly hub a supertrack with no group lands nowhere: UCSC has no native
    # groups for an assembly it does not host, so the track controls come up empty.
    if group:
        overview.append(f"group oridb_{ov['id']}")
    overview += [f"priority {ov.get('priority', 0)}", "", ""]
    out.append("\n".join(overview))

    for t in ov["tracks"]:
        # The overview is declared once for the whole hub, but a dataset exists on
        # the assemblies it was measured on and no others. An overview entry whose
        # dataset is not on this genome is skipped rather than written as a stanza
        # pointing at a file that is not there.
        if datasets and t["dataset"] not in datasets:
            continue
        if t.get("files"):
            # An overview entry that names several files is a comparison, not a
            # profile, and is rendered as a multiWig container exactly as a dataset's
            # own containers are. The case this exists for is a strand pair: plus
            # above the axis and minus below, which only reads as one picture if the
            # two are overlaid in a single row.
            out.append(render_overview_container(t, ov["id"]))
            continue
        lines = [f"track {t['id']}",
                 f"parent oridb_{ov['id']}",
                 f"bigDataUrl {t['dataset']}/{t['file']}",
                 f"shortLabel {t['shortLabel']}",
                 f"longLabel {t['longLabel']}",
                 f"type {t.get('type', 'bigWig')}",
                 f"visibility {t.get('visibility', 'full')}",
                 f"color {t.get('color', '0,0,0')}"]
        if t.get("viewLimits"):
            # Same autoScale choice as a container, with one difference: an overview
            # entry is a stand-alone track, so there is no group of siblings to share a
            # scale with and "group" would be meaningless here.
            auto = t.get("autoScale", "off")
            if auto not in ("off", "on"):
                sys.exit(f"overview track '{t['id']}' has autoScale {auto!r}; a "
                         f"stand-alone track takes only off or on")
            lines += [f"viewLimits {t['viewLimits']}", f"autoScale {auto}",
                      "alwaysZero " + ("on" if auto != "off" else "off"),
                      f"graphTypeDefault {t.get('graphType', 'bar')}",
                      "maxHeightPixels 100:100:8"]
        if t.get("negateValues"):
            lines.append("negateValues on")
        if t.get("yLineMark") is not None:
            lines += ["yLineOnOff on", f"yLineMark {t['yLineMark']}"]
        lines += feature_track_options(t)
        lines += [f"priority {t.get('priority', 10)}", "", ""]
        out.append("\n".join(lines))

    for s in sorted(sections["sections"], key=lambda x: x.get("priority", 99)):
        if f"oridb_{s['id']}" not in used:
            continue
        stanza = [
            f"track oridb_{s['id']}",
            "superTrack on",
            f"shortLabel {s['shortLabel']}",
            f"longLabel {s['longLabel']}",
        ]
        if group:
            stanza.append(f"group oridb_{s['id']}")
        stanza += [f"priority {s.get('priority', 99)}", "", ""]
        out.append("\n".join(stanza))
    return "".join(out)


def sections_in_use(genome_dir, datasets):
    """Which supertracks the datasets present actually claim membership of."""
    used = set()
    for d in datasets:
        for line in open(os.path.join(genome_dir, d, "trackDb.txt")):
            line = line.strip()
            if line.startswith("parent oridb_"):
                used.add(line.split()[1])
    return used


def starter_spec(dataset, bigwig_dir):
    """A spec with one container per file, for a curator to merge into comparisons."""
    tracks = sorted(f for f in os.listdir(bigwig_dir) if f.endswith(".bw"))
    return {
        "dataset": dataset,
        "note": "Starter spec: one container per track. Merge tracks into comparison "
                "containers, set graphType (bar for time courses, points otherwise), "
                "viewLimits and colours, then re-run without --init.",
        "containers": [{
            "id": f[:-3].replace(".", "_"),
            "shortLabel": f[:-3][:17],
            "longLabel": f[:-3],
            "graphType": "points",
            "viewLimits": "0.9:2.1",
            "yLineMark": 1.0,
            "priority": i + 1,
            "tracks": [{"file": f, "shortLabel": f[:-3][:17],
                        "longLabel": f[:-3], "color": "0,0,0"}],
        } for i, f in enumerate(tracks)],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub-root", required=True, help="repository root holding hub.txt")
    ap.add_argument("--genome", default="sacCer3")
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--spec", required=True, help="container spec JSON for this dataset")
    ap.add_argument("--sections", default="docs/sections.json",
                    help="hub-level section (supertrack) definitions, relative to --hub-root")
    ap.add_argument("--bigwig-dir", help="where the .bw files are now (omit to skip copying)")
    ap.add_argument("--dataset-json", help="dataset record to copy in alongside the tracks")
    ap.add_argument("--init", action="store_true",
                    help="write a starter spec from --bigwig-dir and stop")
    a = ap.parse_args()

    if a.init:
        if not a.bigwig_dir:
            sys.exit("--init needs --bigwig-dir")
        with open(a.spec, "w") as fh:
            json.dump(starter_spec(a.dataset, a.bigwig_dir), fh, indent=2)
            fh.write("\n")
        print(f"starter spec written to {a.spec} - edit it, then re-run without --init")
        return

    spec = json.load(open(a.spec))
    sections_path = a.sections if os.path.isabs(a.sections) else os.path.join(a.hub_root, a.sections)
    if not os.path.exists(sections_path):
        sys.exit(f"no sections file at {sections_path}; every container must name a section")
    sections = json.load(open(sections_path))
    section_ids = {s["id"] for s in sections["sections"]}

    dest = os.path.join(a.hub_root, a.genome, a.dataset)
    os.makedirs(dest, exist_ok=True)

    referenced = {t["file"] for c in spec["containers"] for t in c["tracks"]}
    referenced |= {t["file"] for t in spec.get("tracks", [])}
    if a.bigwig_dir:
        for bw in sorted(referenced):
            src = os.path.join(a.bigwig_dir, bw)
            if not os.path.exists(src):
                sys.exit(f"spec references {bw}, which is not in {a.bigwig_dir}")
            if os.path.abspath(src) != os.path.abspath(os.path.join(dest, bw)):
                shutil.copy2(src, os.path.join(dest, bw))
        if a.dataset_json:
            shutil.copy2(a.dataset_json, os.path.join(dest, "dataset.json"))

    missing = [f for f in sorted(referenced) if not os.path.exists(os.path.join(dest, f))]
    if missing:
        sys.exit(f"spec references files not present in {dest}: {missing}")

    with open(os.path.join(dest, "trackDb.txt"), "w") as fh:
        fh.write(render(a.dataset, spec, section_ids))

    genome_dir = os.path.join(a.hub_root, a.genome)
    datasets = sorted(d for d in os.listdir(genome_dir)
                      if os.path.isdir(os.path.join(genome_dir, d))
                      and os.path.exists(os.path.join(genome_dir, d, "trackDb.txt")))
    # Sections first: a supertrack has to be declared before the stanzas that claim it.
    used = sections_in_use(genome_dir, datasets)
    is_assembly_hub = a.genome in assembly_hub_genomes(a.hub_root)
    with open(os.path.join(genome_dir, "sections.trackDb.txt"), "w") as fh:
        fh.write(render_sections(sections, used, datasets, group=is_assembly_hub))
    if is_assembly_hub:
        with open(os.path.join(genome_dir, "groups.txt"), "w") as fh:
            fh.write(render_groups(sections, used))

    with open(os.path.join(genome_dir, "trackDb.txt"), "w") as fh:
        fh.write("# Sections, then one include per dataset. Add a dataset with\n"
                 "# bin/make_trackhub.py; this file is regenerated from the\n"
                 "# directories present.\n\n")
        fh.write("include sections.trackDb.txt\n")
        for d in datasets:
            fh.write(f"include {d}/trackDb.txt\n")

    n_tracks = sum(len(c["tracks"]) for c in spec["containers"])
    n_standalone = len(spec.get("tracks", []))
    print(f"{a.dataset}: {len(spec['containers'])} containers, {n_tracks} track references "
          f"plus {n_standalone} standalone track(s) over {len(referenced)} files "
          f"-> {dest}/trackDb.txt")
    print(f"{a.genome}/trackDb.txt now includes: {', '.join(datasets)}")
    print(f"sections in use: {', '.join(sorted(s[len('oridb_'):] for s in used))} "
          f"(+ overview, the only one open by default)")
    if is_assembly_hub:
        print(f"{a.genome} is an assembly hub: groups.txt regenerated, supertracks grouped")


if __name__ == "__main__":
    main()
